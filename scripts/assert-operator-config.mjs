import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import assert from 'node:assert/strict';
const dist=join(process.cwd(),'dist');
const read = async path => readFile(join(dist,path),'utf8');
const runtime=await read('operator-config.js');
const ga=await read('analytics-config.js');
const home=await read('index.html');
const guide=await read('guides/social-media-character-limits/index.html');
const legal=await read('privacy/index.html');
const native=await read('native-ad-frame.html');
const banner=await read('guide-ad-frame.html');
const ads=await read('ads.txt');
const key=await read('indexnow-key.txt');
const headers=await read('_headers');
assert.match(runtime,/POSTCHARS_OPERATOR_CONFIG/);
assert.match(runtime,/isolated\.invalid\.test\/native-ad-frame\.html/);
assert.match(runtime,/isolated\.invalid\.test\/guide-ad-frame\.html/);
assert.match(ga,/G-TEST0000001/);
assert.match(home,/\/operator-config\.js/);
assert.match(home,/postchars-google-consent-default/);
assert.match(home,/ca-pub-1111111111111111/);
assert.ok(home.indexOf('postchars-google-consent-default')<home.indexOf('adsbygoogle.js'));
assert.doesNotMatch(legal,/adsbygoogle\.js/);
assert.match(guide,/guide-ad-slot/);
assert.match(native,/container-demoads/);
assert.match(native,/ads\.invalid\.test\/native\.js/);
assert.match(banner,/ads\.invalid\.test\/guide\.js/);
assert.match(headers,/frame-ancestors https:\/\/postchars\.com/);
assert.match(ads,/pub-1111111111111111/);
assert.match(key,/aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa/);
const xml=await read('sitemap.xml');
assert.equal([...xml.matchAll(/<loc>/g)].length,42);
console.log('Operator overlay fixture PASS: GA4, AdSense consent ordering, ad frame isolation, guide slots, ads.txt and IndexNow');
